// Formulation code = the registered formulation suffix (SC, WG, GR, EC ...).
export const formCode = (t) => {
  const up = t.toUpperCase()
  if (up.includes('CAPSULE SUSPENSION')) return 'CS'
  const m = up.match(/\b(WDG|WSG|WG|WP|SG|SP|GR|SC|SL|EC|EW|CS|ZC|FS|L)\b/g)
  return m ? m[m.length - 1] : 'SC'
}

